"""Complete the authorized private endpoint once the human has enrolled Tailscale."""
import hashlib,json,os,socket,sqlite3,subprocess,sys,time,urllib.request
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path[:0]=[str(ROOT/'app'),str(ROOT/'experiments')]
from remote_gateway import RemoteGateway,GatewayError
from preferences import Preferences
from paths import DATA
OUT=DATA/'verification/remote-v024';EXE=ROOT/'program/0.24.0/Leva/Leva.exe'
def main():
    gateway=RemoteGateway();state=gateway.status()
    if not state['ready']:
        print(json.dumps({'ready':False,'stage':'device_enrollment','state':state['state']}));return 2
    check=json.loads((OUT/'packaged-check.json').read_text('utf8'))
    if hashlib.sha256(EXE.read_bytes()).hexdigest()!=check['sha256']:raise ValueError('package_changed_after_verification')
    # Never attempt to reconfigure a live desktop from a separate inference host.
    import psutil
    if any(p.info.get('name','').lower()=='leva.exe' for p in psutil.process_iter(['name'])):
        print(json.dumps({'ready':False,'stage':'close_existing_leva_normally'}));return 3
    prefs=Preferences();port=int(prefs.get('web_port'))
    if not port:
        with socket.socket() as probe:probe.bind(('127.0.0.1',0));port=probe.getsockname()[1]
    with socket.socket() as probe:probe.bind(('127.0.0.1',port))
    try:state=gateway.enable(port)
    except GatewayError as error:
        prefs.close();print(json.dumps({'ready':False,'stage':str(error),'setup_url':error.setup_url}));return 4
    backup=DATA/'backups'/('before-remote-activation-'+str(time.time_ns()));backup.mkdir(parents=True)
    with sqlite3.connect(backup/'preferences.sqlite3') as dst:prefs.db.backup(dst)
    prefs.set_many({'web_port':str(port),'web_remote_origin':state['origin'],'web_remote_enabled':True});prefs.close()
    process=subprocess.Popen([str(EXE)],cwd=ROOT,creationflags=0x08000000)
    opener=urllib.request.build_opener(urllib.request.ProxyHandler({}));health=None;failure=''
    for _ in range(20):
        try:
            with opener.open(state['origin']+'/health',timeout=3) as response:health=json.load(response)
            if health.get('desktop_bridge'):break
        except Exception as error:failure=type(error).__name__
        time.sleep(1)
    value={'ready':bool(health and health.get('desktop_bridge')),'origin':state['origin'],'port':port,'pid':process.pid,
           'health':health,'health_failure':failure,'public_funnel':False,'physical_android_tested':False,'next':'Pair Android using a one-time code generated by Leva Desktop.'}
    (OUT/'activation-check.json').write_text(json.dumps(value,ensure_ascii=False,indent=2),'utf8')
    print(json.dumps(value));return 0 if value['ready'] else 5
if __name__=='__main__':raise SystemExit(main())
